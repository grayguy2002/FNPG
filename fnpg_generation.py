def compute_gradient_importance(model, input_data, target_idx=0, device='cuda'):
    """
    使用梯度分析计算特征重要性

    Args:
        model: 训练好的模型
        input_data: 输入数据 (N, C, L)
        target_idx: 目标输出的索引
        device: 计算设备

    Returns:
        importance: 每个输入特征的重要性分数
    """
    model.eval()
    input_tensor = input_data.clone().requires_grad_(True).to(device)

    # 创建Data对象
    data_obj = Data(input_sam=input_tensor, label=None)
    data_obj.x = input_tensor

    # 前向传播
    output = model(data_obj)

    # 对目标输出求和并反向传播
    target_output = output[:, target_idx, :].sum()
    target_output.backward()

    # 计算梯度的绝对值平均作为重要性
    gradients = input_tensor.grad.abs()
    importance = gradients.mean(dim=(0, 2))  # 对样本和序列长度维度求平均

    return importance.cpu().numpy()

def compute_permutation_importance(model, input_data, target_data, feature_names,
                                    n_repeats=5, device='cuda', batch_size=2):
    """
    使用排列重要性计算特征重要性

    Args:
        model: 训练好的模型
        input_data: 输入数据 (N, C, L)
        target_data: 目标数据 (N, C_out, L)
        feature_names: 特征名称列表
        n_repeats: 重复次数
        device: 计算设备
        batch_size: 批处理大小，默认2

    Returns:
        importance_df: 特征重要性 DataFrame
    """
    model.eval()

    # 计算基准MSE - 使用批处理
    with torch.no_grad():
        baseline_preds = []
        for i in range(0, input_data.shape[0], batch_size):
            batch_input = input_data[i:i+batch_size].to(device)
            data_obj = Data(input_sam=batch_input, label=None)
            data_obj.x = batch_input
            batch_pred = model(data_obj)
            # 移除CALI通道（索引0），只保留RSHA, RMED, RDEP, SP
            batch_pred = batch_pred[:, 1:, :]  # 从 (N, 5, L) 变为 (N, 4, L)
            baseline_preds.append(batch_pred.cpu())

        baseline_pred = torch.cat(baseline_preds, dim=0)

        # 确保维度匹配
        if baseline_pred.shape[0] != target_data.shape[0]:
            # 只对齐样本数量维度
            min_samples = min(baseline_pred.shape[0], target_data.shape[0])
            baseline_pred = baseline_pred[:min_samples]
            target_aligned = target_data[:min_samples]
        else:
            target_aligned = target_data

        # 确保 target_aligned 也在 CPU 上，与 baseline_pred 保持一致
        target_aligned = target_aligned.cpu()

        baseline_mse = F.mse_loss(baseline_pred, target_aligned).item()

    importance_scores = {name: [] for name in feature_names}

    for feat_idx, feat_name in enumerate(feature_names):
        for _ in range(n_repeats):
            # 创建打乱后的输入
            shuffled_input = input_data.clone()
            perm = torch.randperm(shuffled_input.shape[0])
            shuffled_input[:, feat_idx, :] = shuffled_input[perm, feat_idx, :]

            # 计算打乱后的MSE - 使用批处理
            with torch.no_grad():
                shuffled_preds = []
                for i in range(0, shuffled_input.shape[0], batch_size):
                    batch_shuffled = shuffled_input[i:i+batch_size].to(device)
                    data_obj = Data(input_sam=batch_shuffled, label=None)
                    data_obj.x = batch_shuffled
                    batch_pred = model(data_obj)
                    # 移除CALI通道（索引0），只保留RSHA, RMED, RDEP, SP
                    batch_pred = batch_pred[:, 1:, :]  # 从 (N, 5, L) 变为 (N, 4, L)
                    shuffled_preds.append(batch_pred.cpu())

                shuffled_pred = torch.cat(shuffled_preds, dim=0)
                shuffled_mse = F.mse_loss(shuffled_pred, target_aligned).item()

            # 重要性 = MSE增加量
            importance = shuffled_mse - baseline_mse
            importance_scores[feat_name].append(importance)

    # 创建结果DataFrame
    results = []
    for feat_name in feature_names:
        scores = importance_scores[feat_name]
        results.append({
            'Feature': feat_name,
            'Importance_Mean': np.mean(scores),
            'Importance_Std': np.std(scores),
            'Importance_Min': np.min(scores),
            'Importance_Max': np.max(scores)
        })

    importance_df = pd.DataFrame(results).sort_values('Importance_Mean', ascending=False)
    return importance_df, baseline_mse

