def compute_sample_statistics(tensor_data, feature_names, dataset_name="Dataset"):
    """
    计算数据集的统计信息

    Args:
        tensor_data: 数据张量 (N, C, L) 或 list of tensors
        feature_names: 特征名称列表
        dataset_name: 数据集名称

    Returns:
        stats_df: 统计信息 DataFrame
    """
    if isinstance(tensor_data, list):
        # 如果是tensor列表，先合并
        tensor_data = torch.cat(tensor_data, dim=0)

    if isinstance(tensor_data, torch.Tensor):
        data = tensor_data.cpu().numpy()
    else:
        data = tensor_data

    # 如果是3D张量 (N, C, L)
    if len(data.shape) == 3:
        N, C, L = data.shape
        n_samples = N
        seq_length = L
        # 重塑为 (N*L, C) 用于统计
        data_flat = data.transpose(0, 2, 1).reshape(-1, C)
    else:
        n_samples = data.shape[0]
        seq_length = 1
        data_flat = data
        C = data.shape[1] if len(data.shape) > 1 else 1

    print("\n" + "="*60)
    print(f"{dataset_name} 统计信息")
    print("="*60)
    print(f"样本数量 (N): {n_samples}")
    print(f"序列长度 (L): {seq_length}")
    print(f"特征数量 (C): {len(feature_names)}")
    print(f"总数据点数: {n_samples * seq_length}")

    # 计算每个特征的统计信息
    stats_dict = {
        'Feature': feature_names,
        'Mean': [],
        'Std': [],
        'Min': [],
        'Max': [],
        'Median': [],
        'Q1 (25%)': [],
        'Q3 (75%)': [],
        'Skewness': [],
        'Kurtosis': []
    }

    for i, name in enumerate(feature_names):
        feature_data = data_flat[:, i]
        stats_dict['Mean'].append(np.mean(feature_data))
        stats_dict['Std'].append(np.std(feature_data))
        stats_dict['Min'].append(np.min(feature_data))
        stats_dict['Max'].append(np.max(feature_data))
        stats_dict['Median'].append(np.median(feature_data))
        stats_dict['Q1 (25%)'].append(np.percentile(feature_data, 25))
        stats_dict['Q3 (75%)'].append(np.percentile(feature_data, 75))
        stats_dict['Skewness'].append(stats.skew(feature_data))
        stats_dict['Kurtosis'].append(stats.kurtosis(feature_data))

    stats_df = pd.DataFrame(stats_dict)
    print("\n特征统计信息:")
    print(stats_df.to_string(index=False))

    return stats_df

def plot_feature_distributions(tensor_data, feature_names, dataset_name="Dataset",
                                save_path=None, bins=50):
    """
    绘制特征分布直方图

    Args:
        tensor_data: 数据张量
        feature_names: 特征名称列表
        dataset_name: 数据集名称
        save_path: 保存路径
        bins: 直方图的bin数量
    """
    if isinstance(tensor_data, list):
        tensor_data = torch.cat(tensor_data, dim=0)

    if isinstance(tensor_data, torch.Tensor):
        data = tensor_data.cpu().numpy()
    else:
        data = tensor_data

    if len(data.shape) == 3:
        N, C, L = data.shape
        data_flat = data.transpose(0, 2, 1).reshape(-1, C)
    else:
        data_flat = data
        C = data.shape[1] if len(data.shape) > 1 else 1

    n_features = len(feature_names)
    n_cols = min(4, n_features)
    n_rows = (n_features + n_cols - 1) // n_cols

    fig, axes = plt.subplots(n_rows, n_cols, figsize=(4*n_cols, 3*n_rows))
    if n_features == 1:
        axes = [axes]
    else:
        axes = axes.flatten()

    for i, name in enumerate(feature_names):
        ax = axes[i]
        feature_data = data_flat[:, i]

        # 使用更宽松的百分位数范围（0.5%-99.5%）来移除极端异常值
        p_low = np.percentile(feature_data, 0.5)
        p_high = np.percentile(feature_data, 99.5)

        # 使用range参数限制直方图的数据范围
        ax.hist(feature_data, bins=bins, range=(p_low, p_high), density=True, alpha=0.7,
                color='steelblue', edgecolor='black', linewidth=0.5)
        ax.axvline(np.mean(feature_data), color='red', linestyle='--',
                   label=f'Mean: {np.mean(feature_data):.2f}')
        ax.axvline(np.median(feature_data), color='green', linestyle=':',
                   label=f'Median: {np.median(feature_data):.2f}')
        ax.set_xlabel(name, fontsize=10)
        ax.set_ylabel('Density', fontsize=10)
        ax.set_title(f'{name} Distribution', fontsize=11)
        ax.legend(fontsize=8)
        ax.grid(True, alpha=0.3)

    # 隐藏多余的子图
    for i in range(n_features, len(axes)):
        axes[i].set_visible(False)

    plt.suptitle(f'{dataset_name} Feature Distributions', fontsize=14, y=1.02)
    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"分布图已保存至: {save_path}")

    plt.show()

def compare_train_test_statistics(train_data, test_data, feature_names, save_path=None):
    """
    比较训练集和测试集的统计特性

    Args:
        train_data: 训练数据张量
        test_data: 测试数据张量
        feature_names: 特征名称列表
        save_path: 保存路径
    """
    # 计算统计信息
    train_stats = compute_sample_statistics(train_data, feature_names, "Training Set")
    test_stats = compute_sample_statistics(test_data, feature_names, "Test Set")

    # 可视化对比
    n_features = len(feature_names)
    fig, axes = plt.subplots(2, n_features, figsize=(4*n_features, 8))

    if isinstance(train_data, torch.Tensor):
        train_np = train_data.cpu().numpy()
        test_np = test_data.cpu().numpy()
    else:
        train_np = train_data
        test_np = test_data

    if len(train_np.shape) == 3:
        train_flat = train_np.transpose(0, 2, 1).reshape(-1, train_np.shape[1])
        test_flat = test_np.transpose(0, 2, 1).reshape(-1, test_np.shape[1])
    else:
        train_flat = train_np
        test_flat = test_np

    for i, name in enumerate(feature_names):
        # 直方图对比
        ax1 = axes[0, i] if n_features > 1 else axes[0]
        ax1.hist(train_flat[:, i], bins=50, density=True, alpha=0.5,
                 label='Train', color='blue')
        ax1.hist(test_flat[:, i], bins=50, density=True, alpha=0.5,
                 label='Test', color='orange')
        ax1.set_title(f'{name}', fontsize=11)
        ax1.set_xlabel('Value')
        ax1.set_ylabel('Density')
        ax1.legend()
        ax1.grid(True, alpha=0.3)

        # 箱线图对比
        ax2 = axes[1, i] if n_features > 1 else axes[1]
        bp = ax2.boxplot([train_flat[:, i], test_flat[:, i]],
                         labels=['Train', 'Test'], patch_artist=True)
        bp['boxes'][0].set_facecolor('lightblue')
        bp['boxes'][1].set_facecolor('lightorange')
        ax2.set_title(f'{name} Comparison', fontsize=11)
        ax2.set_ylabel('Value')
        ax2.grid(True, alpha=0.3)

    plt.suptitle('Train vs Test Distribution Comparison', fontsize=14, y=1.02)
    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"对比图已保存至: {save_path}")

    plt.show()

    return train_stats, test_stats

