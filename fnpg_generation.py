class InverseTransformer:
    """
    反标准化工具类，将预测值转换回原始量级
    """
    def __init__(self, standard_data_path=None):
        """
        Args:
            standard_data_path: 标准化参数文件路径
        """
        self.group_stats = {}  # 存储组标准化参数
        self.global_stats = {}  # 存储全局标准化参数

        if standard_data_path:
            self.load_standard_params(standard_data_path)

    def load_standard_params(self, path):
        """加载标准化参数"""
        standard_data = pd.read_csv(path)
        for col in standard_data.columns:
            if col != 'WELL':
                self.global_stats[col] = {
                    'mean': standard_data[col].mean(),
                    'std': standard_data[col].std()
                }
        print(f"已加载标准化参数: {list(self.global_stats.keys())}")

    def set_feature_stats(self, feature_name, mean, std):
        """手动设置特征的标准化参数"""
        self.global_stats[feature_name] = {'mean': mean, 'std': std}

    def inverse_transform(self, data, feature_name):
        """
        反标准化单个特征

        Args:
            data: 标准化后的数据 (tensor 或 numpy array)
            feature_name: 特征名称

        Returns:
            反标准化后的数据
        """
        if feature_name not in self.global_stats:
            print(f"警告: 未找到 {feature_name} 的标准化参数，返回原始数据")
            return data

        mean = self.global_stats[feature_name]['mean']
        std = self.global_stats[feature_name]['std']

        if isinstance(data, torch.Tensor):
            return data * std + mean
        else:
            return data * std + mean

    def inverse_transform_batch(self, data, feature_names):
        """
        批量反标准化多个特征

        Args:
            data: 标准化后的数据 (N, C, L) 或 (C, L)
            feature_names: 特征名称列表

        Returns:
            反标准化后的数据
        """
        if isinstance(data, torch.Tensor):
            result = data.clone()
        else:
            result = data.copy()

        for i, name in enumerate(feature_names):
            if len(data.shape) == 3:
                result[:, i, :] = self.inverse_transform(data[:, i, :], name)
            elif len(data.shape) == 2:
                result[i, :] = self.inverse_transform(data[i, :], name)

        return result

    def report_transform_stats(self, original, transformed, feature_names):
        """
        报告原始数据和反标准化数据的统计信息对比
        """
        print("\n" + "="*60)
        print("R2-3: 逆变换统计对比")
        print("="*60)
        print(f"{'Feature':<15} {'Original Mean':<15} {'Transformed Mean':<15} {'Original Std':<15} {'Transformed Std':<15}")
        print("-"*75)

        for i, name in enumerate(feature_names):
            if len(original.shape) == 3:
                orig_data = original[:, i, :].flatten()
                trans_data = transformed[:, i, :].flatten()
            else:
                orig_data = original[i, :].flatten()
                trans_data = transformed[i, :].flatten()

            if isinstance(orig_data, torch.Tensor):
                orig_data = orig_data.cpu().numpy()
                trans_data = trans_data.cpu().numpy()

            print(f"{name:<15} {np.mean(orig_data):<15.4f} {np.mean(trans_data):<15.4f} "
                  f"{np.std(orig_data):<15.4f} {np.std(trans_data):<15.4f}")

