def compute_metrics_per_well(predictions, targets, well_indices=None):
    """
    计算每口井的评估指标

    Args:
        predictions: 预测值 (N, C, L) 或 list of tensors
        targets: 目标值 (N, C, L) 或 list of tensors
        well_indices: 井的索引列表，用于分割数据

    Returns:
        metrics_df: 每口井的指标 DataFrame
    """
    if isinstance(predictions, torch.Tensor):
        predictions = predictions.cpu().numpy()
    if isinstance(targets, torch.Tensor):
        targets = targets.cpu().numpy()

    # 如果是3D数据，展平
    if len(predictions.shape) == 3:
        N, C, L = predictions.shape
        predictions = predictions.reshape(N, -1)
        targets = targets.reshape(N, -1)

    metrics_list = []

    if well_indices is None:
        # 如果没有井索引，将整个数据作为一口井
        well_indices = [(0, len(predictions))]

    for well_id, (start, end) in enumerate(well_indices):
        pred = predictions[start:end].flatten()
        targ = targets[start:end].flatten()

        # 计算各种指标
        mse = np.mean((pred - targ) ** 2)
        rmse = np.sqrt(mse)
        mae = np.mean(np.abs(pred - targ))

        # R² (决定系数)
        ss_res = np.sum((targ - pred) ** 2)
        ss_tot = np.sum((targ - np.mean(targ)) ** 2)
        r2 = 1 - (ss_res / ss_tot) if ss_tot > 0 else 0

        # Pearson 相关系数
        if np.std(pred) > 0 and np.std(targ) > 0:
            pearson_r, pearson_p = stats.pearsonr(pred, targ)
        else:
            pearson_r, pearson_p = 0, 1

        metrics_list.append({
            'Well_ID': well_id,
            'MSE': mse,
            'RMSE': rmse,
            'MAE': mae,
            'R2': r2,
            'Pearson_R': pearson_r,
            'Pearson_P': pearson_p,
            'N_Samples': end - start
        })

    return pd.DataFrame(metrics_list)

