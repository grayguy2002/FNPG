def compute_correlation_matrix(input_tensor, target_tensor, input_names, target_names,
                                method='pearson', save_path=None):
    """
    计算输入特征与输出目标之间的相关性矩阵

    Args:
        input_tensor: 输入数据 (N, C_in, L) 或 (N, C_in)
        target_tensor: 目标数据 (N, C_out, L) 或 (N, C_out)
        input_names: 输入特征名称列表
        target_names: 输出特征名称列表
        method: 'pearson' 或 'spearman'
        save_path: 保存图片的路径

    Returns:
        corr_matrix: 相关性矩阵 DataFrame
    """
    # 转换为 numpy 并展平
    if isinstance(input_tensor, torch.Tensor):
        input_data = input_tensor.cpu().numpy()
        target_data = target_tensor.cpu().numpy()
    else:
        input_data = input_tensor
        target_data = target_tensor

    # 如果是3D张量，需要重塑
    if len(input_data.shape) == 3:
        N, C_in, L = input_data.shape
        input_data = input_data.transpose(0, 2, 1).reshape(-1, C_in)  # (N*L, C_in)
    if len(target_data.shape) == 3:
        N, C_out, L = target_data.shape
        target_data = target_data.transpose(0, 2, 1).reshape(-1, C_out)  # (N*L, C_out)

    # 合并数据
    all_names = input_names + target_names
    all_data = np.concatenate([input_data, target_data], axis=1)

    # 创建 DataFrame
    df = pd.DataFrame(all_data, columns=all_names)

    # 计算相关性矩阵
    if method == 'pearson':
        corr_matrix = df.corr(method='pearson')
    else:
        corr_matrix = df.corr(method='spearman')

    # 可视化
    fig, axes = plt.subplots(1, 2, figsize=(16, 6))

    # 完整相关性矩阵
    sns.heatmap(corr_matrix, annot=True, cmap='RdBu_r', center=0,
                fmt='.2f', ax=axes[0], vmin=-1, vmax=1,
                annot_kws={'size': 8})
    axes[0].set_title(f'Full Correlation Matrix ({method.capitalize()})', fontsize=12)

    # 输入-输出相关性矩阵（只显示输入与输出之间的相关性）
    input_output_corr = corr_matrix.loc[input_names, target_names]
    sns.heatmap(input_output_corr, annot=True, cmap='RdBu_r', center=0,
                fmt='.2f', ax=axes[1], vmin=-1, vmax=1,
                annot_kws={'size': 10})
    axes[1].set_title(f'Input-Output Correlation ({method.capitalize()})', fontsize=12)
    axes[1].set_xlabel('Output Features')
    axes[1].set_ylabel('Input Features')

    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"相关性矩阵图已保存至: {save_path}")

    plt.show()

    # 打印关键统计信息
    print("\n" + "="*60)
    print("输入-输出相关性分析摘要")
    print("="*60)
    for target in target_names:
        print(f"\n{target} 与输入特征的相关性:")
        for inp in input_names:
            corr_val = corr_matrix.loc[inp, target]
            strength = "强" if abs(corr_val) > 0.7 else ("中等" if abs(corr_val) > 0.4 else "弱")
            print(f"  {inp}: {corr_val:.4f} ({strength}相关)")

    return corr_matrix

