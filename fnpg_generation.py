class ComputationalEfficiencyTracker:
    """
    跟踪模型推理的计算效率指标
    """
    def __init__(self, device):
        self.device = device
        self.inference_times = []
        self.memory_usage = []
        self.batch_sizes = []
        self.total_samples = 0

    def start_tracking(self):
        """开始跟踪"""
        if self.device.type == 'cuda':
            torch.cuda.synchronize()
            torch.cuda.reset_peak_memory_stats()
        self.start_time = time.time()
        self.start_memory = self._get_memory_usage()

    def end_tracking(self, batch_size):
        """结束跟踪"""
        if self.device.type == 'cuda':
            torch.cuda.synchronize()

        end_time = time.time()
        end_memory = self._get_memory_usage()

        inference_time = end_time - self.start_time
        memory_used = end_memory - self.start_memory

        self.inference_times.append(inference_time)
        self.memory_usage.append(memory_used)
        self.batch_sizes.append(batch_size)
        self.total_samples += batch_size

    def _get_memory_usage(self):
        """获取当前内存使用量 (MB)"""
        if self.device.type == 'cuda':
            return torch.cuda.memory_allocated(self.device) / (1024 ** 2)
        else:
            import psutil
            return psutil.Process().memory_info().rss / (1024 ** 2)

    def get_peak_memory(self):
        """获取峰值内存使用量 (MB)"""
        if self.device.type == 'cuda':
            return torch.cuda.max_memory_allocated(self.device) / (1024 ** 2)
        else:
            return max(self.memory_usage) if self.memory_usage else 0

    def report(self):
        """生成效率报告"""
        total_time = sum(self.inference_times)
        avg_time_per_batch = np.mean(self.inference_times) if self.inference_times else 0
        avg_time_per_sample = total_time / self.total_samples if self.total_samples > 0 else 0
        throughput = self.total_samples / total_time if total_time > 0 else 0

        print("\n" + "="*60)
        print("R2-1: 计算效率指标报告")
        print("="*60)
        print(f"设备: {self.device}")
        print(f"总推理样本数: {self.total_samples}")
        print(f"总推理时间: {total_time:.4f} 秒")
        print(f"平均每批次时间: {avg_time_per_batch*1000:.2f} 毫秒")
        print(f"平均每样本时间: {avg_time_per_sample*1000:.4f} 毫秒")
        print(f"吞吐量: {throughput:.2f} 样本/秒")
        print(f"峰值内存使用: {self.get_peak_memory():.2f} MB")

        if self.device.type == 'cuda':
            print(f"GPU: {torch.cuda.get_device_name(self.device)}")
            print(f"GPU总内存: {torch.cuda.get_device_properties(self.device).total_memory / (1024**3):.2f} GB")

        return {
            'total_samples': self.total_samples,
            'total_time_sec': total_time,
            'avg_time_per_batch_ms': avg_time_per_batch * 1000,
            'avg_time_per_sample_ms': avg_time_per_sample * 1000,
            'throughput_samples_per_sec': throughput,
            'peak_memory_mb': self.get_peak_memory()
        }

